total = 0
for fname in BLOCK_FILES:
    path = os.path.join(BASE, "blocks", fname)
    t = io.open(path, encoding="utf-8").read()
    lines = t.split("\n")
    changed = 0
    for i, line in enumerate(lines):
        m = re.match(r"^##\s+Вопрос\s+(\d+)[.:]", line)
        if m:
            n = int(m.group(1))
            if n in TITLES:
                new = "## Вопрос " + str(n) + ". " + TITLES[n]
                if lines[i] != new:
                    lines[i] = new
                    changed += 1
    if changed:
        io.open(path, "w", encoding="utf-8").write("\n".join(lines))
    total += changed
    print(fname, "headings updated:", changed)
print("TOTAL updated:", total)
